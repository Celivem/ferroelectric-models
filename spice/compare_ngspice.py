# ------------------------------------------------------------ running
def find_ngspice() -> str | None:
    env = os.environ.get("NGSPICE")
    if env and Path(env).exists():
        return env
    for name in ("ngspice_con", "ngspice"):
        exe = shutil.which(name)
        if exe:
            return exe
    return None


def ensure_osdi() -> Path:
    env = os.environ.get("FECAP_OSDI")
    if env and Path(env).exists():
        BUILD.mkdir(parents=True, exist_ok=True)
        if Path(env).resolve() != OSDI.resolve():
            shutil.copy(env, OSDI)
        return OSDI
    src = HERE / "fecap_nls.va"
    if OSDI.exists() and OSDI.stat().st_mtime >= src.stat().st_mtime:
        return OSDI
    sys.path.insert(0, str(HERE))
    import build_osdi

    return build_osdi.build(16, OSDI, quiet=True)


def write_decks(decks=None):
    TESTS_DIR.mkdir(exist_ok=True)
    for d in decks or all_decks():
        (TESTS_DIR / f"{d.name}.cir").write_text(d.text(), encoding="utf-8", newline="\n")


def run_deck(deck: Deck, ngspice: str) -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    TESTS_DIR.mkdir(exist_ok=True)
    deck_path = TESTS_DIR / f"{deck.name}.cir"
    if not deck_path.exists() or deck_path.read_text(encoding="utf-8") != deck.text():
        deck_path.write_text(deck.text(), encoding="utf-8", newline="\n")
    t0 = time.time()
    r = subprocess.run([ngspice, "-b", str(deck_path)], cwd=OUT, capture_output=True, text=True, errors="replace")
    elapsed = time.time() - t0
    (OUT / f"{deck.name}.log").write_text(r.stdout + r.stderr, encoding="utf-8")
    datname = f"{deck.name}.dat" if deck.analysis == "tran" else "leakage_25C.dat"
    if r.returncode != 0 or not (OUT / datname).exists():
        raise RuntimeError(f"ngspice failed on {deck.name}; see {OUT / (deck.name + '.log')}")
    rows, store = [], {}
    deck.compare(read_dat(OUT / datname), rows, store)
    warn = [ln for ln in (r.stdout + r.stderr).splitlines() if "singular" in ln.lower() or "timestep too small" in ln.lower()]
    return {"name": deck.name, "title": deck.title, "ngspice_seconds": round(elapsed, 2), "checks": rows,
            "warnings": warn, "store": store}


def run(names=None, verbose=True):
    ngspice = find_ngspice()
    if ngspice is None:
        raise SystemExit("ngspice not found: set NGSPICE or put ngspice_con on PATH")
    ensure_osdi()
    decks = [d for d in all_decks() if not names or d.name in names]
    results = []
    for d in decks:
        res = run_deck(d, ngspice)
        results.append(res)
        if verbose:
            print(f"== {res['name']}: {res['title']}  (ngspice {res['ngspice_seconds']} s)")
            for c in res["checks"]:
                flag = "ok  " if c["ok"] else "FAIL"
                kind = "rel" if c["relative"] else "abs"
                print(f"   {flag} {c['quantity']}: ngspice {c['ngspice']:.6g}, python {c['python']:.6g}, "
                      f"diff {c['difference']:.3g} ({kind} tol {c['tolerance']:g})")
            for w in res["warnings"]:
                print("   warning:", w)
    summary = [{k: v for k, v in r.items() if k != "store"} for r in results]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "results.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    return results


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    if "--write-decks" in sys.argv:
        write_decks()
        print("decks written to", TESTS_DIR)
    else:
        res = run(args or None)
        n_bad = sum(not c["ok"] for r in res for c in r["checks"])
        n_all = sum(len(r["checks"]) for r in res)
        print(f"{n_all - n_bad}/{n_all} checks passed")
        sys.exit(1 if n_bad else 0)
