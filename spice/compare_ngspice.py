def deck_leakage():
    inst = Instance("DC sweep", np.array([0.0, 1.0]), np.array([0.0, 0.0]), -1.0)
    extra = "\n".join([
        "dc V1 -3 3 0.05",
        "wrdata leakage_25C.dat i(v1)",
        "set temp = 85",
        "option temp = 85",
        "dc V1 -3 3 0.05",
        "wrdata leakage_85C.dat i(v1)",
    ])

    def compare(d25, rows, store):
        d85 = read_dat(OUT / "leakage_85C.dat")
        out = {}
        for lab, d, temp in (("25 C", d25, 298.15), ("85 C", d85, 358.15)):
            vn = d["v-sweep"] if "v-sweep" in d else d[list(d)[0]]
            i_ng = -d["i(v1)"]
            i_py = AREA * nm.j_leak(P, vn, temp)
            m = np.abs(vn) > 0.04
            err = np.max(np.abs(i_ng[m] - i_py[m]) / np.abs(i_py[m]))
            check(rows, f"max relative |I_ngspice - I_python|, {lab}", err, 0.0, 1e-6)
            out[lab] = (vn, i_ng, i_py)
        check(rows, "I(2 V) at 25 C [A]", np.interp(2.0, *out["25 C"][:2]), AREA * nm.j_leak(P, 2.0), 1e-6, rel=True)
        store.update(series=out)

    return Deck("leakage", "Leakage I-V by DC sweep at 25 C and 85 C", [inst], 0.0, 0.0, analysis="dc",
                extra=extra, compare=compare,
                options="* leakage currents are ~1e-16-1e-10 A: tighten the absolute current tolerance\n"
                        ".options abstol=1e-20 gmin=1e-25")


